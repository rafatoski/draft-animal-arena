// Copies the deterministic game rules into the Supabase Edge Function bundle, adding the ".ts" extensions Deno requires.
// Run `npm run sync:shared` after touching src/simulation, src/game/{config,fighters,series,onlineSim}.ts.
// tests/server.test.mjs fails if the committed copy is stale.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

export const SHARED = ['simulation/random.ts', 'simulation/combat.ts', 'game/config.ts', 'game/fighters.ts', 'game/series.ts', 'game/abilities.ts', 'game/upgrades.ts', 'game/onlineSim.ts']
export const OUT = 'supabase/functions/_shared'
export function transform(source) {
  return `// GENERATED by scripts/sync-shared.mjs from src/. Do not edit.\n` + source.replace(/from '(\.[^']+)'/g, "from '$1.ts'")
}
if (import.meta.url === `file://${process.argv[1]}`) {
  for (const file of SHARED) {
    mkdirSync(dirname(`${OUT}/${file}`), { recursive: true })
    writeFileSync(`${OUT}/${file}`, transform(readFileSync(`src/${file}`, 'utf8')))
  }
  console.log(`synced ${SHARED.length} files to ${OUT}`)
}
